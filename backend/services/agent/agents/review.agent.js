import { HumanMessage, SystemMessage } from "@langchain/core/messages";
import { providerManager } from "../providers/providerManager.js";
import { createLogger } from "../../../shared/logger/logger.js";

const logger = createLogger("review-agent");

export const reviewAgent = async (state) => {
  logger.info("Executing Review & Validation Agent");

  const unreviewedContent = state.response || "";
  if (!unreviewedContent || unreviewedContent.length < 50) {
    return state;
  }

  const messages = [
    new SystemMessage(`You are the Zen AI Review and Validation Agent.
Your job is to audit output generated by peer agents (such as Coding, Document, or Research agents) for:
1. Technical accuracy and completeness.
2. Security issues (XSS, SQL injection, hardcoded secrets, unsafe regex).
3. Code formatting and cleanliness.

If the output is already high quality and complete, return the output unchanged.
If critical fixes or security enhancements are required, provide the refined output with an appended "### ✅ Security & Quality Audit" section.`),
    new HumanMessage(`Original Output:\n${unreviewedContent}\n\nUser Context:\n${state.prompt}`),
  ];

  try {
    const result = await providerManager.invoke(messages, {
      agent: "review",
      model: state.modelPreference,
    });

    return {
      ...state,
      response: result.content,
      reviewed: true,
    };
  } catch (err) {
    logger.warn("Review validation step skipped due to error", { error: err.message });
    return state;
  }
};

export default reviewAgent;
